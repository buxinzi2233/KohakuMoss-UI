"""Official ml-gbc coordinate compatibility; real resolver/native worker, no models."""

import copy
import hashlib
import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from test_gbc_data import PYTHON, REPO, graph, png

from kohakumoss_ui.contract.gbc_data import DataError, call

FIXTURE = REPO / "KohakuGBC/tests/graph/fixtures/mlgbc_cases.jsonl.gz"
FIXTURE_SHA256 = "1e3316cef39e13899148e4b353e49fdd108f80562c47e5be2604f034b9e6f53a"
FIRST_CASE = "v1b_haiku55_gdinotiny_fp16/Ilish_Bhaat.jpg"


class GbcDataBboxTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not FIXTURE.is_file() or not PYTHON.is_file():
            raise unittest.SkipTest("Official sibling GBC fixture and native runtime required")
        cls.keep = bool(os.environ.get("GBC_DATA_EVIDENCE"))
        cls.root = Path(tempfile.mkdtemp(prefix="bbox-data-", dir=os.environ.get("GBC_DATA_EVIDENCE")))
        # Official test_resolution.py identifies this corpus as generated by ml-gbc.
        # Use its real reference resolver and digest, not the review's derived copy.
        code = """
import gzip, hashlib, json, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
from kohakugbc.graph.reference import resolve
from kohakugbc.graph.digest import digest
source, output = Path(sys.argv[2]), Path(sys.argv[3])
index, graphs = [], []
with gzip.open(source, 'rt', encoding='utf-8') as stream:
    for line in stream:
        case = json.loads(line)
        if 'error' in case:
            continue
        value = resolve(case['records'], case['img_path'], case.get('img_size'))
        if not value or not value.get('img_size'):
            continue
        assert digest(value) == case['digest'], case['name']
        index.append({'case': case['name'], 'digest': case['digest']})
        graphs.append(value)
(output / 'official.jsonl').write_text(''.join(json.dumps(g) + '\\n' for g in graphs))
(output / 'source.json').write_text(json.dumps({'fixture': str(source),
    'sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'index': index}))
assert 'torch' not in sys.modules
print(json.dumps({'resolved': len(graphs), 'torchImported': False}))
"""
        done = subprocess.run([str(PYTHON), "-I", "-B", "-c", code,
                               str(REPO / "KohakuGBC/src"), str(FIXTURE), str(cls.root)],
                              capture_output=True, text=True, timeout=30, check=False)
        (cls.root / "resolver.stdout").write_text(done.stdout, encoding="ascii")
        (cls.root / "resolver.stderr").write_text(done.stderr, encoding="utf-8")
        if done.returncode:
            raise AssertionError(done.stderr)
        cls.jsonl = cls.root / "official.jsonl"
        cls.source = json.loads((cls.root / "source.json").read_text())
        cls.graphs = [json.loads(line) for line in cls.jsonl.read_text().splitlines()]
        cls.first = cls.graphs[next(i for i, row in enumerate(cls.source["index"]) if row["case"] == FIRST_CASE)]

    @classmethod
    def tearDownClass(cls):
        if not cls.keep:
            shutil.rmtree(cls.root)
        else:
            print(f"GBC_BBOX_EVIDENCE={cls.root}")

    def setUp(self):
        self.case = Path(tempfile.mkdtemp(prefix="case-", dir=self.root))

    def preview(self, value):
        path = self.case / "graph.jsonl"
        path.write_text(json.dumps(value) + "\n", encoding="ascii")
        return call(PYTHON, {"action": "graph_page", "path": str(path)})["items"][0]["graph"]

    def test_all_official_sized_graphs_preserve_original_coordinates(self):
        self.assertEqual(self.source["sha256"], FIXTURE_SHA256)
        self.assertEqual(len(self.graphs), 89)
        before = hashlib.sha256(self.jsonl.read_bytes()).hexdigest()
        page = call(PYTHON, {"action": "graph_page", "path": str(self.jsonl), "limit": 128})
        self.assertEqual(len(page["items"]), 89)
        self.assertIsNone(page["nextOffset"])
        outside_cases = 0
        for original, item in zip(self.graphs, page["items"]):
            preview = item["graph"]
            self.assertEqual(preview["bboxSpace"], "normalized-ltrb")
            self.assertEqual(preview["bboxDisplayPolicy"], "clip-to-image")
            self.assertEqual([n["bbox"] for n in preview["nodes"]], [v["bbox"] for v in original["vertices"]])
            outside_cases += any(n["outside"] for n in preview["nodes"])
            for node in preview["nodes"]:
                expected = {k: max(0, min(1, node["bbox"][k])) for k in ("left", "top", "right", "bottom")}
                self.assertEqual(node["displayBbox"], expected)
        self.assertEqual(outside_cases, 9)
        self.assertEqual(hashlib.sha256(self.jsonl.read_bytes()).hexdigest(), before)
        result = {"officialDigestVerified": 89, "workerAccepted": 89, "outsideCases": outside_cases,
                  "originalCoordinatesPreserved": True, "fixtureSha256": self.source["sha256"]}
        (self.root / "official-result.json").write_text(json.dumps(result, indent=2), encoding="ascii")

    def test_official_bbox_survives_native_pack_validate_page(self):
        # Synthetic raster, same real stored dimensions; only img_path is adapted.
        # This is storage/geometry testing, NOT claimed generation of its caption.
        image = self.case / "image.png"
        image.write_bytes(png(*self.first["img_size"]))
        value = copy.deepcopy(self.first)
        value["img_path"] = str(image)
        source = self.case / "graph.jsonl"
        source.write_text(json.dumps(value) + "\n", encoding="ascii")
        before = source.read_bytes()
        output = self.case / "packed"
        call(PYTHON, {"action": "pack", "graphs": str(source), "imageRoot": str(self.case),
                      "output": str(output), "records": [{"key": "official", "image": str(image),
                                                           "meta": {"fixtureCase": FIRST_CASE}}]})
        inspected = call(PYTHON, {"action": "inspect", "path": str(output)})
        self.assertIsNone(inspected["validatedSamples"])
        checked = call(PYTHON, {"action": "validate", "path": str(output)})
        self.assertEqual(checked["validatedSamples"], 1)
        preview = call(PYTHON, {"action": "page", "path": str(output)})["items"][0]["graph"]
        node = next(n for n in preview["nodes"] if n["id"] == "fish fillets_3")
        self.assertEqual(node["bbox"]["top"], -0.00018310546875)
        self.assertTrue(node["outside"])
        self.assertEqual(node["displayBbox"]["top"], 0)
        self.assertEqual(source.read_bytes(), before)
        code = """
import json,sys
from kohakugbc_data.dataset import GbcDataset
with GbcDataset(sys.argv[1],image=None) as ds:
    value=json.loads(ds.graph('official').to_json())
    print(json.dumps({v['vertex_id']:v['bbox'] for v in value['vertices']}))
"""
        readback = subprocess.run([str(PYTHON), "-I", "-B", "-c", code, str(output)],
                                  capture_output=True, text=True, timeout=30, check=False)
        self.assertEqual(readback.returncode, 0, readback.stderr)
        stored = json.loads(readback.stdout)
        self.assertEqual(stored, {v["vertex_id"]: v["bbox"] for v in self.first["vertices"]})
        (self.root / "official-native-readback.json").write_text(readback.stdout, encoding="ascii")

    def test_subpixel_policy_is_dimension_aware_and_not_unbounded(self):
        value = graph(self.case / "unused.png")
        value["img_size"] = [1024, 1024]
        value["vertices"][1]["bbox"]["top"] = -0.49 / 1024
        self.assertTrue(self.preview(value)["nodes"][1]["outside"])
        for size, top in (([1024, 1024], -0.51 / 1024), ([1, 1], -0.02)):
            with self.subTest(size=size, top=top):
                value["img_size"] = size
                value["vertices"][1]["bbox"]["top"] = top
                with self.assertRaises(DataError) as caught:
                    self.preview(value)
                self.assertEqual(caught.exception.code, "invalid_graph")

    def test_reversed_nonfinite_extreme_and_fully_outside_rejected(self):
        invalid = [
            {"left": 0.8, "right": 0.2}, {"top": 0.5, "bottom": 0.5},
            {"top": float("nan")}, {"top": float("inf")}, {"bottom": -float("inf")},
            {"left": -1e100}, {"right": 1e100}, {"top": True},
            {"left": 1.001, "right": 1.002}, {"top": -0.002, "bottom": -0.001},
        ]
        for changes in invalid:
            with self.subTest(changes=changes):
                value = graph(self.case / "unused.png")
                value["vertices"][1]["bbox"].update(changes)
                with self.assertRaises(DataError):
                    self.preview(value)


if __name__ == "__main__":
    unittest.main()
